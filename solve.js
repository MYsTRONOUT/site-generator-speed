// A fast drop-in for makefun-site 1.0.0: run(input) returns exactly the answer
// makefun-site's build returns, for every input. Same rules, same output, byte
// for byte — but written to be fast: a single-pass Markdown renderer with
// run-based escaping, a character-driven lexer, cached slugs, and front matter
// parsed without splitting the whole body. No dependencies, Node 22 stdlib only.
//
// The semantics follow makefun-site's own README and reference code (front
// matter grammar, template dialect, Markdown subset, slug rule, report). Where
// a rule has an edge case, this file takes the same branch the reference does.

